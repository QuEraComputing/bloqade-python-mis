"""
Generators of sandpile and percolation-based clustering on graphs, for use
in cluster update monte carlo optimization of graphs.

@author: jwurtz
"""
import networkx as nx
import numpy as np

class sandpile(list):
    """
    A generalized sandpile simulator, which generates self-organized critical
    clusters on a graph. See https://www.nature.com/articles/s41598-018-20275-7
    """
    def __init__(self,graph:nx.Graph,dissapation = 0.05):
        """
        graph - a networkx graph
        dissapation - A dissipation value which removes sand grains with
                       some small probability.
        """
        
        self.graph = graph
        self.dissapation = dissapation
        self.N = graph.number_of_nodes()
        
        self.adjacency = {a:list(b.keys()) for a,b in dict(graph.adjacency()).items()}
        
        # Validate that the graph labels are integers from 0 to N-1...
        if len(set(graph.nodes).difference(set(range(self.N))))!=0:
            raise ValueError("graph index labels are not integers from 0 t N-1")
            
        degree = dict(graph.degree)
        self.threshold = np.zeros(self.N)
        self.threshold[list(degree.keys())] = list(degree.values())
        
        
        self.lookup_F = np.array(list(graph.nodes))
        self.lookup_R = np.zeros(self.N)
        self.lookup_R[self.lookup_F] = np.arange(self.N) # Note that this assumes that the values are integers from 0 to N-1
        
        self.density = np.zeros(self.N)
        
        self(epochs = 2)
        del self[0:self.N]
    
    
    def next(self):
        """
        Get the next cluster as generated by a sandpile model
        inplace:
            Adds a cluster to the list of clusters in self.
        returns
        cluster: set - A set of all vertices in the sandpile cluster.
        """
        
        # Add until a sandpile collapses...
        while np.all(self.density<self.threshold):
            self.density[np.random.choice(self.N)] += 1
        
        # Iteratively collapse the sandpile...
        cluster = set()
        while np.any(self.density>=self.threshold):
            targets = np.where(self.density>=self.threshold)[0]
            
            for target in np.random.permutation(targets):
                cluster.add(target)
                self.density[target] -= self.threshold[target]
                
                for neighbor in self.adjacency[target]:
                    if np.random.rand()>self.dissapation:
                        self.density[neighbor] += 1
        self.append(cluster)
        return cluster
    
    def __call__(self,epochs:float = 1.0):
        """
        Repeatedly generate clusters to return a cluster which is hopefully
        uncorrelated with any previous (is every cluster correlated??).
        
        Inputs:
        epochs:float (1) -
            The number of epochs to repeat. Ultimately this generates
             epochs*Nvertices clusters.
                  
        Returns:
        cluster: set - A set of all vertices in the sandpile cluster.
        """
        for ctr in range(max([1,int(epochs*self.N)])):
            self.next()
        return self[-1]
    
    def distribution(self):
        """
        Counts the distribution of cluster sizes
        returns
        counts : list[float] The probability of each cluster size
        """
        lens = [len(q) for q in self]
        counts,vals = np.histogram(lens,bins=self.N+1,range=[0,self.N+1],density=True)
        
        return counts
    
class percolation:
    """
    Compute a cluster based on edge-dropout percolation. Note that we want the
    dropout to be near the percolition threshold, where the
    distribution of clusters is scale-free, which for King's graphs is around 0.3.
    
    """
    def __init__(self,graph:nx.Graph):
        """
        graph:nx.Graph
            The graph on which to percolate
        """
        self.graph = graph
                  
    def __call__(self,dropout:float):
        """
        dropout:float
            The edge dropout probability. If this dropout is at the critical threshold,
            the distribution over clusters will be scale-free.
        
        returns:
            cluster: set - A set of all vertices in the percolation cluster.
        """
        
        graph = self.graph
        
        N = len(graph.nodes)
        edgelist = np.array(graph.edges)
        
        # 1. Create a percolated graph by randomly dropping edges
        perm = np.random.permutation(len(graph.edges))
    
        percolated_graph = nx.Graph(edgelist[perm[0:int(dropout*len(graph.edges))]].tolist())
        percolated_graph.add_nodes_from(range(N))
        
        # 2. Identify the cluster update by selecting a random node (e.g.
        #     select a random cluster weighted by its size)
        center = np.random.choice(len(graph.nodes))
        cluster = set([q for q in list(nx.connected_components(percolated_graph)) if center in percolated_graph][0])
        
        return cluster
            
            
        