from bloqade import start
from bloqade.ir import var


class tempering_MIS_solution(Solution):
    
    def __init__(self, problem:unit_disk_maximum_independent_set, backend={}):
        """
        Quantum implementation of maximum independent set using tempering
        problem - a UDGMIS problem instance
        """
        print("hello world")
        super().__init__(problem,backend)
        self.problem = problem
        self._backend = backend
        
        
        self.cluster_generator = postprocess.utils.clustering.sandpile(self.problem.graph)
    
    
    def ansatz(self,quantum_parameters:dict):
        
        atom_positions = logical_to_physical(
                positions = self.problem.positions,
                graph = self.problem.graph,
                radius = 8.0)
        atom_positions = [tuple(q) for q in atom_positions]
        
        time = quantum_parameters["time"]
        initial_detuning = quantum_parameters["initial_detuning"]
        final_detuning = quantum_parameters["final_detuning"]
        
        program_unassigned = start.add_position(atom_positions) \
            .rydberg.rabi.amplitude.uniform.piecewise_linear(
                durations = [var("time")*0.2,var("time")*.6,0.2*var("time")],
                values = [0., 15, 15, 0.0])\
            .detuning.uniform.piecewise_linear(
                durations = [var("time")*0.2,var("time")*.6,0.2*var("time")],
                values = ["initial_detuning","initial_detuning", "final_detuning","final_detuning"])
            
        program_assigned = program_unassigned.assign(
            time=time,
            initial_detuning= initial_detuning,
            final_detuning  = final_detuning)
        
        return program_assigned
    
    
    def get_solution(self,quantum_parameters:dict, classical_parameters:dict)-> tuple[list[set],list[set]]:
        """
        Computes an independent set solution based on a parallel tempering algorithm
        with cluster updates.
        Clusters are selected through percolation near criticality (https://www.nature.com/articles/s41598-018-20275-7)
        Internals of the cluster are replaced with a parallel solution drawn
        from measurement outcomes from the quantum machine.
        
        classical parameters required:
            epochs - Number of epochs to do for simulated annealing. Total number
                        of steps is [epochs] * [nvertices]
            temperature - Effective simulated annealing temperature to accept/reject
                        updates. Units of 1, the independent set size.
            percolation_dropout - Probability to keep each edge when computing
                        the subcluster based on edge dropout percolation.
                        Note that for a Kings graph, I find heuristically that
                        the critical threshold is somewhere between 0.35 and 0.40.
        
        Returns:
            solutions - List of solutions generated by the simulated annealing algorithm.
                        Each item is a binary vector as an independent set solution to the graph

        """
        
        if classical_parameters.keys()!=set(self.classical_parameters):
            raise KeyError("Missing keys!")
        
        # Extract bitstrings from the quantum device
        bitstrings = self.get_bitstrings(quantum_parameters)[0]
        
        
        # Identify properties of the graph (technically this can be done at initialization)
        N = len(self.problem.graph.nodes)
        adj = nx.adjacency_matrix(self.problem.graph)
        edgelist = np.array((self.problem.graph.edges))
        
        # Iterate through some number of epochs of simulated annealing
        solution = set()
        self.updates = []
        solutions = []
        nsteps = int(np.ceil(classical_parameters["epochs"]*N))
        for epoch in range(nsteps):
            # Draw a bitstring as a candidate solution (eg from the "high temperature reservoir")
            bstr = bitstrings[np.random.choice(len(bitstrings))]
            parallel_solution = set(np.where(bstr==0)[0])

            

            candidate_solution = {a for a in solution}
            
            # Compute the cluster based on a sandpile model (self orginized criticality)
            
            if isinstance(self.cluster_generator,postprocess.utils.clustering.sandpile):
                internal = self.cluster_generator()
            elif isinstance(self.cluster_generator,postprocess.utils.clustering.percolation):
                internal = self.cluster_generator(classical_parameters["percolation_dropout"])
            else:
                raise RuntimeError("Unknown cluster generator instance:",self.cluster_generator)
            
            
            # External nodes are those which are outside of the cluster
            external = set(self.problem.graph.nodes).difference(internal)
            
            # 3. The internal independent set is from the parallel solution,
            #     while the external independent set is from the current solution
            #     similar to a Houdayer cluster move
            internal_mIS = internal.intersection(parallel_solution)
            external_mIS = external.intersection(solution)
            
            # 4. Merge the internal and external independent sets. Note that this
            #     step might have a more efficient implementation by only reconciling
            #     the boundary. This is done by selecting the ordering of a greedy MIS
            #     by first adding the external IS vertices, then randomly adding
            #     the internal IS vertices. Note that this preserves the condition
            #     that solutions be independent sets; if the parallel solution
            #     is not an independent set, it will instead provide a greedy
            #     independent set biased by the parallel solution.
            #     This greedy solver is zero-local and is unaware of connectivity.
            ordering = list(external_mIS) + np.random.permutation(list(internal_mIS)).tolist()
            candidate_solution = get_mIS(self.problem.graph, ordering)
            
            # 5. Accept or reject the cluster update based on the temperature.
            #     The temperature is in units of 1, the independent set size.
            if np.exp(np.min([1,(len(candidate_solution) - len(solution))*classical_parameters["beta"]]))>np.random.rand():
                solution = {a for a in candidate_solution}
            solutions.append(solution)
            
            self.updates.append(internal)
        
        # Parse solutions into binary vectors
        solution_out = []
        for sol in solutions:
            tmp = np.zeros(self.problem.graph.number_of_nodes())
            tmp[list(sol)] = 1
            solution_out.append(tmp)
            
        return solution_out
    
    
    
    def objective(self,quantum_parameters:dict, classical_parameters:dict = {}):
        
        value = 0
        for ctr in range(10): # Average over 10 rounds
            solns = self.get_solution(quantum_parameters,classical_parameters)
            value += -np.average([self.problem.cost(soln) for soln in solns])
        return value / (ctr + 1)
    
    @property
    def classical_parameters(self):
        return ["epochs","beta"]
    
    @property
    def quantum_parameters(self):
        return ["time","initial_detuning","final_detuning"]



class classical_tempering_MIS_solution(tempering_MIS_solution):
    
    def get_bitstrings(self,quantum_parameters={}):
        
        if quantum_parameters["sampling"]=="all":
            return [[np.zeros(len(self.problem.graph.nodes))]]
        elif quantum_parameters["sampling"]=="greedy0":
            bitstrings = []
            for ctr in range(1000):
                sol = get_mIS(self.problem.graph)
                
                candidate = np.ones(len(self.problem.graph.nodes))
                candidate[list(sol)] = 0
                bitstrings.append(candidate)
            return [bitstrings]
        
        elif quantum_parameters["sampling"]=="greedy1":
            bitstrings = []
            for ctr in range(1000):
                
                
                sol = greedy_mIS(self.problem.graph)
                # Add some noise on top
                N = len(self.problem.graph.nodes)
                toadd = set(np.random.permutation(N)[0:int(N/5)])
                toremove = set(np.random.permutation(N)[0:int(N/3)])
                sol = sol.union(toadd)
                sol = sol.difference(toremove)
                
                candidate = np.ones(len(self.problem.graph.nodes))
                candidate[list(sol)] = 0
                bitstrings.append(candidate)
            return [bitstrings]
        else:
            raise ValueError("Bad sampling parameter!",quantum_parameters["sampling"])
            
    @property
    def quantum_parameters(self):
        """
        Sampling key must be:
            - "all": The all-zeros bitstring
            - "greedy0": Zero-local greedy add
            - "greedy1": One-local greedy add
        """

        return ["sampling"]